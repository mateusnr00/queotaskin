-- Cria o pool de CPFs pré-cadastrados. Cada cadastro novo (registerAction)
-- claim atomicamente uma linha via `FOR UPDATE SKIP LOCKED` e copia o CPF
-- pro User.cpf, o usuário NÃO digita CPF mais. Quando o pool esgotar, o
-- cadastro continua funcionando (User.cpf fica NULL e a reserva pede como
-- já fazia).
--
-- A semente abaixo (559 CPFs) é importada de uma planilha curada; todos
-- passam no algoritmo dos dígitos verificadores. ON CONFLICT DO NOTHING
-- evita explosão se a migration rodar 2x (não deveria, mas é barato).

CREATE TABLE "CpfPool" (
    "id" TEXT NOT NULL,
    "cpf" TEXT NOT NULL,
    "assignedUserId" TEXT,
    "assignedAt" TIMESTAMP(3),
    "createdAt" TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT "CpfPool_pkey" PRIMARY KEY ("id")
);

CREATE UNIQUE INDEX "CpfPool_cpf_key" ON "CpfPool"("cpf");
CREATE UNIQUE INDEX "CpfPool_assignedUserId_key" ON "CpfPool"("assignedUserId");
CREATE INDEX "CpfPool_assignedUserId_idx" ON "CpfPool"("assignedUserId");

